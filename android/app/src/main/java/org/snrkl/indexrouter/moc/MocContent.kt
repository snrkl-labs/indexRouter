package org.snrkl.indexrouter.moc

/**
 * The text of a Map of Content note, and the rules for its backups.
 *
 * A MoC lists its folder with a Dataview query rather than a static list, so it
 * stays correct as recordings arrive without the app rewriting anything. That is
 * the same principle as the daily note: this app writes on demand, never on a
 * webhook, and nothing outside its own folder is touched.
 *
 * No Android types: covered by JVM unit tests.
 */
object MocContent {

    const val BACKUP_STAMP_PATTERN = "yyyyMMddHHmmss"

    /** File name for a folder's MoC. Folder-qualified so wikilinks stay unambiguous. */
    fun mocFileName(folderName: String): String = "$folderName MoC.md"

    /**
     * Icon for a reserved folder's map, in the frontmatter property the vault
     * already uses for this (`displayIcon: LiCalendarDays` on the daily note).
     *
     * Only the reserved folders get one: a rule folder's contents are whatever
     * the user decided they are, and an icon that means nothing is worse than none.
     * The folders themselves are icon'd by hand — that state lives in a plugin's
     * data under `.obsidian/`, which this app does not write to.
     */
    fun iconFor(folderName: String, taskDir: String, fallbackDir: String, audioDir: String): String? =
        when (folderName) {
            taskDir -> "LiCheckSquare"
            fallbackDir -> "LiInbox"
            audioDir -> "LiMic"
            else -> null
        }

    /** A child folder's map, linking back up to the root index. */
    fun childBody(
        folderName: String,
        folderPath: String,
        rootMocName: String,
        icon: String? = null,
    ): String = buildString {
        appendLine("---")
        appendLine("source: pebble-index-01")
        appendLine("type: moc")
        appendLine("folder: \"$folderPath\"")
        icon?.let { appendLine("displayIcon: $it") }
        appendLine("---")
        appendLine()
        appendLine("# $folderName")
        appendLine()
        appendLine("Up: [[${rootMocName.removeSuffix(".md")}]]")
        appendLine()
        appendLine("```dataview")
        appendLine("TABLE created, routed-by AS \"routed by\"")
        appendLine("FROM \"$folderPath\"")
        appendLine("WHERE type != \"moc\"")
        appendLine("SORT created DESC")
        appendLine("```")
        appendLine()
        appendLine(GENERATED_NOTE)
    }

    /** The index of indexes at the base folder. */
    fun rootBody(baseName: String, basePath: String, children: List<Pair<String, String>>): String = buildString {
        appendLine("---")
        appendLine("source: pebble-index-01")
        appendLine("type: moc")
        appendLine("folder: \"$basePath\"")
        appendLine("---")
        appendLine()
        appendLine("# $baseName")
        appendLine()
        if (children.isEmpty()) {
            appendLine("No folders are included in the map yet.")
        } else {
            children.forEach { (folderName, count) ->
                appendLine("- [[${mocFileName(folderName).removeSuffix(".md")}|$folderName]] — $count")
            }
        }
        appendLine()
        appendLine(GENERATED_NOTE)
    }

    /**
     * The block that pulls today's voice tasks into a daily note.
     *
     * Scoped to the app's own folder rather than matched by tag: daily notes
     * written before v0.2.0 still contain inline task lines carrying the same
     * tag, and a tag-matched query would render those a second time in the very
     * section meant to replace them. The trade is that the path is baked in, so
     * this is generated by the app — which knows the current base folder — rather
     * than written out by hand once and left to go stale.
     */
    fun dailyNoteTaskQuery(basePath: String): String = buildString {
        appendLine("```dataview")
        appendLine("TASK")
        appendLine("FROM \"$basePath\"")
        appendLine("WHERE !completed AND file.day = this.file.day")
        appendLine("SORT file.name ASC")
        appendLine("```")
    }

    /** Ready-to-paste query for a folder, dropped beside the content it queries. */
    fun proForma(folderName: String, folderPath: String, basePath: String, isTaskFolder: Boolean): String = buildString {
        appendLine("---")
        appendLine("source: pebble-index-01")
        appendLine("type: query-proforma")
        appendLine("---")
        appendLine()
        appendLine("# $folderName — ready-to-paste views")
        appendLine()
        appendLine("> [!warning] This file is generated and will be overwritten.")
        appendLine("> Do not edit it. Copy a block into your own note or template;")
        appendLine("> that copy is yours, this one is disposable.")
        appendLine()
        appendLine("## Copy these")
        appendLine()
        appendLine("**Everything, newest first**")
        appendLine()
        appendLine("````")
        appendLine("```dataview")
        appendLine("TABLE created, routed-by AS \"routed by\"")
        appendLine("FROM \"$folderPath\"")
        appendLine("SORT created DESC")
        appendLine("```")
        appendLine("````")
        appendLine()
        appendLine("**Open tasks from here**")
        appendLine()
        appendLine("````")
        appendLine("```dataview")
        appendLine("TASK")
        appendLine("FROM \"$folderPath\"")
        appendLine("WHERE !completed")
        appendLine("```")
        appendLine("````")

        if (isTaskFolder) {
            appendLine()
            appendLine("**Today's tasks, for the daily note**")
            appendLine()
            appendLine("Paste this under the daily note template's task heading. It is scoped to")
            appendLine("`$basePath`, so tasks written into daily notes by older versions are not")
            appendLine("listed twice.")
            appendLine()
            appendLine("````")
            append(dailyNoteTaskQuery(basePath))
            appendLine("````")
        }

        // The same queries, live, so what they return can be seen here rather
        // than only after pasting them somewhere.
        appendLine()
        appendLine("## What they show")
        appendLine()
        appendLine("Rendered below, for looking at — not for copying.")
        appendLine()
        appendLine("**Everything, newest first**")
        appendLine()
        appendLine("```dataview")
        appendLine("TABLE created, routed-by AS \"routed by\"")
        appendLine("FROM \"$folderPath\"")
        appendLine("SORT created DESC")
        appendLine("```")
        appendLine()
        appendLine("**Open tasks from here**")
        appendLine()
        appendLine("```dataview")
        appendLine("TASK")
        appendLine("FROM \"$folderPath\"")
        appendLine("WHERE !completed")
        appendLine("```")

        if (isTaskFolder) {
            appendLine()
            appendLine("**Today's tasks**")
            appendLine()
            appendLine("This one is empty here and populated in a daily note — by design.")
            appendLine("It matches on the note's own date, and this file is not a date.")
            appendLine()
            append(dailyNoteTaskQuery(basePath))
        }
    }

    fun backupName(mocFileName: String, timestamp: String): String = "$mocFileName.$timestamp.bak"

    /**
     * Which backups to delete so that [keep] remain. Oldest go first, and the
     * timestamp sorts lexicographically because it is fixed-width.
     */
    fun backupsToPrune(existing: List<String>, mocFileName: String, keep: Int): List<String> {
        val mine = existing.filter { it.startsWith("$mocFileName.") && it.endsWith(".bak") }.sorted()
        val excess = mine.size - keep.coerceAtLeast(1)
        return if (excess > 0) mine.take(excess) else emptyList()
    }

    private const val GENERATED_NOTE =
        "*Generated by the routing app. Rebuilding replaces this file; the previous " +
            "copy is kept in `.backups`.*"
}

/**
 * The app's [MaterialTheme].
 *
 * Dynamic colour is preferred where the platform offers it, which on the target
 * GrapheneOS Pixel is always; the palette in Color.kt is the fallback, seeded
 * from the launcher icon so the app looks like itself either way.
 */
@Composable
internal fun IndexRouterTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColors
        else -> LightColors
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = AppTypography,
        shapes = AppShapes,
        content = content,
    )
}
